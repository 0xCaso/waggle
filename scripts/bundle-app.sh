#!/usr/bin/env bash
# Wrap the built Waggle executable in a macOS app bundle under apps/macos/.build,
# embedding Sparkle.framework and the daemon binary, then sign the bundle (Developer ID, else ad-hoc).
set -euo pipefail

# Prints the "version" field of a package.json to stdout.
extract_version() {
    grep '"version"' "$1" | head -1 | sed -E 's/.*"version"[[:space:]]*:[[:space:]]*"([^"]+)".*/\1/'
}

# Escapes the three XML-significant characters for a plist string value.
xml_escape() {
    printf '%s' "$1" | sed -e 's/&/\&amp;/g' -e 's/</\&lt;/g' -e 's/>/\&gt;/g'
}

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
APP_DIR="$ROOT/apps/macos"
BUILD_DIR="$APP_DIR/.build"

# Prefer a release build when present; the default `swift build` is debug.
# KNOCK_EXECUTABLE overrides this so update-e2e.sh can point at the exact binary
# it just built (a stale release build must never be bundled by mistake).
EXEC="${KNOCK_EXECUTABLE:-}"
if [ -z "$EXEC" ]; then
    EXEC="$BUILD_DIR/debug/Knock"
    if [ -f "$BUILD_DIR/release/Knock" ]; then
        EXEC="$BUILD_DIR/release/Knock"
    fi
fi

if [ ! -f "$EXEC" ]; then
    echo "error: Waggle executable not found at $EXEC" >&2
    echo "Run 'swift build' in apps/macos first." >&2
    exit 1
fi

BUNDLE="$BUILD_DIR/Waggle.app"
rm -rf "$BUNDLE"
mkdir -p "$BUNDLE/Contents/MacOS" "$BUNDLE/Contents/Resources" "$BUNDLE/Contents/Frameworks"
# The SwiftPM product is still called Knock (HAIL-171 keeps the module name); the bundle executable
# is Waggle, so Activity Monitor and the Dock say Waggle.
cp "$EXEC" "$BUNDLE/Contents/MacOS/Waggle"

# The app icon (HAIL-23). A release build uses the plain icon; every other
# build uses the DEV-banded icon (HAIL-26), generated by the same script.
if [ "${KNOCK_RELEASE:-0}" = "1" ]; then
    ICON="$APP_DIR/Resources/AppIcon.icns"
else
    ICON="$APP_DIR/Resources/AppIcon-dev.icns"
fi
if [ ! -f "$ICON" ]; then
    echo "error: $ICON not found - run scripts/make-app-icon.sh (with --dev for a dev build) first." >&2
    exit 1
fi
cp "$ICON" "$BUNDLE/Contents/Resources/AppIcon.icns"

# SwiftPM resources (the bundled Inter and JetBrains Mono fonts) live in
# Knock_Knock.bundle next to the executable. Copy it into Contents/Resources,
# where FontRegistration looks. Without it the app falls back to system fonts
# (0.1.9 crashed on every Mac but the build machine: Bundle.module found the
# bundle only through its absolute .build path).
RESOURCE_BUNDLE="$(dirname "$EXEC")/Knock_Knock.bundle"
if [ -d "$RESOURCE_BUNDLE" ]; then
    rm -rf "$BUNDLE/Contents/Resources/Knock_Knock.bundle"
    ditto "$RESOURCE_BUNDLE" "$BUNDLE/Contents/Resources/Knock_Knock.bundle"
else
    echo "error: $RESOURCE_BUNDLE not found (fonts); run swift build first." >&2
    exit 1
fi

# The app starts `waggle daemon` on demand from Contents/Resources/waggle
# (docs/SERVICE.md). Ship the compiled daemon there so the bundled app can.
# KNOCK_DAEMON_BINARY overrides the source (scripts/update-e2e.sh builds N and
# N+1 daemons with different baked-in versions).
DAEMON="${KNOCK_DAEMON_BINARY:-$ROOT/daemon/dist/waggle}"
if [ -f "$DAEMON" ]; then
    cp "$DAEMON" "$BUNDLE/Contents/Resources/waggle"
    # HAIL-176: while LEGACY_KNOCK_ALIASES is on, the old command name stays: `knock` is a link to
    # the same binary. An old shim, a ~/.local/bin/knock link or a Claude desktop entry that still
    # names Contents/Resources/knock keeps working after an in-place update.
    if grep -q 'LEGACY_KNOCK_ALIASES = true' "$ROOT/daemon/src/protocol/legacy-aliases.ts"; then
        ln -s waggle "$BUNDLE/Contents/Resources/knock"
    fi
else
    echo "warning: $DAEMON not found - build it with 'cd daemon && bun run build'." >&2
    echo "warning: the app's on-demand start will not work until it is present." >&2
fi

# The Waggle Claude Code plugin ships inside the app as a self-contained local
# marketplace (HAIL-135): Contents/Resources/claude-plugin/.claude-plugin/marketplace.json
# plus the plugin in ./waggle. `waggle install claude` points Claude Code at it.
# Tests and the plugin's own tsconfig stay out of the bundle.
PLUGIN_SRC="$ROOT/plugins/claude-code"
PLUGIN_DEST="$BUNDLE/Contents/Resources/claude-plugin"
mkdir -p "$PLUGIN_DEST/.claude-plugin"
cp "$PLUGIN_SRC/bundle/marketplace.json" "$PLUGIN_DEST/.claude-plugin/marketplace.json"
mkdir -p "$PLUGIN_DEST/waggle"
(cd "$PLUGIN_SRC/waggle" && tar --exclude='*.test.*' --exclude='tsconfig.json' --exclude='node_modules' --exclude='.DS_Store' -cf - .) \
    | (cd "$PLUGIN_DEST/waggle" && tar -xf -)
chmod +x "$PLUGIN_DEST/waggle/bin/waggle-launcher"

# The Waggle Codex plugin ships the same way (HAIL-137): Contents/Resources/codex-plugin is a
# local marketplace (.agents/plugins/marketplace.json) with the plugin in ./waggle.
# `waggle install codex` adds it with `codex plugin marketplace add` when Codex has `codex plugin`.
CODEX_SRC="$ROOT/plugins/codex"
CODEX_DEST="$BUNDLE/Contents/Resources/codex-plugin"
mkdir -p "$CODEX_DEST/.agents/plugins"
cp "$CODEX_SRC/bundle/.agents/plugins/marketplace.json" "$CODEX_DEST/.agents/plugins/marketplace.json"
mkdir -p "$CODEX_DEST/waggle"
(cd "$CODEX_SRC/waggle" && tar --exclude='*.test.*' --exclude='node_modules' --exclude='.DS_Store' -cf - .) \
    | (cd "$CODEX_DEST/waggle" && tar -xf -)
chmod +x "$CODEX_DEST/waggle/bin/waggle-launcher"

# Sparkle.framework comes from Sparkle's SwiftPM binary target (KNOCK-21). The
# xcframework is universal (arm64 + x86_64); take the framework out of the
# first slice and embed it so @rpath resolves at launch.
XCFRAMEWORK="$BUILD_DIR/artifacts/sparkle/Sparkle/Sparkle.xcframework"
SPARKLE_FRAMEWORK=""
for slice in "$XCFRAMEWORK"/*/Sparkle.framework; do
    if [ -d "$slice" ]; then SPARKLE_FRAMEWORK="$slice"; break; fi
done
if [ -z "$SPARKLE_FRAMEWORK" ]; then
    echo "error: Sparkle.framework not found under $XCFRAMEWORK" >&2
    echo "Run 'swift build' in apps/macos first (it fetches Sparkle)." >&2
    exit 1
fi
# ditto preserves the framework's symlinks (Versions/Current etc.).
ditto "$SPARKLE_FRAMEWORK" "$BUNDLE/Contents/Frameworks/Sparkle.framework"

# The executable links @rpath/Sparkle.framework/...; teach the rpath where the
# framework lives inside the bundle so the app launches from Finder.
install_name_tool -add_rpath "@executable_path/../Frameworks" "$BUNDLE/Contents/MacOS/Waggle"

# Version source: CFBundleShortVersionString matches the daemon's package.json
# version (the app compares the two for the KNOCK-21 handoff). CFBundleVersion is
# a monotonically increasing build number; release.sh bumps it.
VERSION="${KNOCK_CFBUNDLE_SHORT_VERSION:-$(extract_version "$ROOT/daemon/package.json")}"
BUILD_NUMBER="${KNOCK_CFBUNDLE_VERSION:-$(cat "$APP_DIR/Resources/BuildNumber")}"

# Name and bundle id (HAIL-26). A release build is "Waggle" with id
# dev.limone.knock (the id keeps the old name so an update stays in place); every other build is "Waggle Dev" with a ".dev" id suffix,
# unless KNOCK_BUNDLE_ID is set (the e2e test uses it so Sparkle's user
# defaults never touch the real dev.limone.knock domain).
if [ "${KNOCK_RELEASE:-0}" = "1" ]; then
    APP_NAME="Waggle"
    BUNDLE_ID="${KNOCK_BUNDLE_ID:-dev.limone.knock}"
else
    APP_NAME="Waggle Dev"
    BUNDLE_ID="${KNOCK_BUNDLE_ID:-dev.limone.knock.dev}"
fi

# The e2e test serves its appcast over http://127.0.0.1 (no certificate for
# https). That needs an ATS exception, which must never appear in a real build:
# it is emitted only when KNOCK_E2E=1 (update-e2e.sh), never for a release.
ATS_BLOCK=""
if [ "${KNOCK_E2E:-0}" = "1" ]; then
    ATS_BLOCK='    <key>NSAppTransportSecurity</key>
    <dict>
        <key>NSAllowsArbitraryLoads</key>
        <true/>
    </dict>'
fi

# The e2e test launches the app through LaunchServices (`open`), which drops the
# shell environment, and Sparkle's relaunch drops it again. Baking the temp
# KNOCK_HOME and the immediate-check hook into LSEnvironment (e2e only, never a
# release) keeps every launch on the temp data root and forces the first
# background check.
LS_ENV_BLOCK=""
if [ "${KNOCK_E2E:-0}" = "1" ]; then
    LS_ENV_BLOCK='    <key>LSEnvironment</key>
    <dict>
        <key>KNOCK_UPDATE_CHECK_NOW</key>
        <string>1</string>'
    if [ "${KNOCK_E2E_SELF_RENAME:-0}" = "1" ]; then
        LS_ENV_BLOCK="$LS_ENV_BLOCK
        <key>KNOCK_E2E_SELF_RENAME</key>
        <string>1</string>"
    fi
    if [ -n "${KNOCK_E2E_HOME:-}" ]; then
        LS_ENV_BLOCK="$LS_ENV_BLOCK
        <key>KNOCK_HOME</key>
        <string>$(xml_escape "$KNOCK_E2E_HOME")</string>"
    fi
    if [ -n "${KNOCK_E2E_RESTART_FILE:-}" ]; then
        LS_ENV_BLOCK="$LS_ENV_BLOCK
        <key>KNOCK_EVIDENCE_UPDATE_RESTART_FILE</key>
        <string>$(xml_escape "$KNOCK_E2E_RESTART_FILE")</string>"
    fi
    LS_ENV_BLOCK="$LS_ENV_BLOCK
    </dict>"
fi

# Feed and public key are release-only inputs (KNOCK-17 fold pass 2). A dev or
# local build (build-local.sh, a plain bundle-app.sh) embeds neither, so the app
# never starts Sparkle and never shows an update alert. Only a release build
# (KNOCK_RELEASE=1: release.sh and update-e2e.sh) embeds SUFeedURL and
# SUPublicEDKey.
FEED_URL=""
PUBLIC_KEY=""
SU_BLOCK=""
if [ "${KNOCK_RELEASE:-0}" = "1" ]; then
    FEED_URL="${KNOCK_FEED_URL:-https://github.com/waggle-so/waggle-releases/releases/latest/download/appcast.xml}"
    PUBLIC_KEY="${KNOCK_SPARKLE_PUBLIC_KEY:-}"
    if [ -z "$PUBLIC_KEY" ] && [ -f "$ROOT/scripts/sparkle-public-key" ]; then
        PUBLIC_KEY="$(cat "$ROOT/scripts/sparkle-public-key")"
    fi
    if [ -z "$PUBLIC_KEY" ]; then
        echo "error: KNOCK_SPARKLE_PUBLIC_KEY is required for a release build." >&2
        echo "Run generate_keys once (docs/RELEASE.md) and pass its public key." >&2
        exit 1
    fi
    FEED_URL="$(xml_escape "$FEED_URL")"
    PUBLIC_KEY="$(xml_escape "$PUBLIC_KEY")"
    SU_BLOCK="    <key>SUFeedURL</key>
    <string>$FEED_URL</string>
    <key>SUPublicEDKey</key>
    <string>$PUBLIC_KEY</string>
    <key>SUEnableAutomaticChecks</key>
    <true/>
    <key>SUAutomaticallyUpdate</key>
    <true/>
    <key>SUScheduledCheckInterval</key>
    <integer>3600</integer>"
fi

cat > "$BUNDLE/Contents/Info.plist" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>CFBundleIdentifier</key>
    <string>$BUNDLE_ID</string>
    <key>CFBundleName</key>
    <string>$APP_NAME</string>
    <key>CFBundleDisplayName</key>
    <string>$APP_NAME</string>
    <key>CFBundleExecutable</key>
    <string>Waggle</string>
    <key>CFBundleIconFile</key>
    <string>AppIcon</string>
    <key>CFBundlePackageType</key>
    <string>APPL</string>
    <key>CFBundleShortVersionString</key>
    <string>$VERSION</string>
    <key>CFBundleVersion</key>
    <string>$BUILD_NUMBER</string>
    <key>LSMinimumSystemVersion</key>
    <string>14.0</string>
    <key>LSUIElement</key>
    <false/>
    <key>CFBundleURLTypes</key>
    <array>
        <dict>
            <key>CFBundleURLName</key>
            <string>$BUNDLE_ID</string>
            <key>CFBundleURLSchemes</key>
            <array>
                <string>waggle</string>
            </array>
        </dict>
    </array>
$SU_BLOCK$ATS_BLOCK$LS_ENV_BLOCK</dict>
</plist>
EOF

# Signing. Identity: KNOCK_SIGN_IDENTITY, else the first "Developer ID Application" identity in the
# keychain, else ad-hoc ("-"). A Developer ID signature gives the app a stable designated
# requirement, so macOS keeps its privacy permissions across updates. An ad-hoc signature has a
# cdhash requirement that changes on every build.
SIGN_IDENTITY="${KNOCK_SIGN_IDENTITY:-}"
if [ -z "$SIGN_IDENTITY" ]; then
    SIGN_IDENTITY="$(security find-identity -v -p codesigning 2>/dev/null \
        | awk '/"Developer ID Application/ { print $2; exit }')"
fi
SIGN_IDENTITY="${SIGN_IDENTITY:--}"

if [ "$SIGN_IDENTITY" = "-" ]; then
    echo "bundle-app.sh: signing ad-hoc (no Developer ID Application identity)" >&2
    # UNUserNotificationCenter (KNOCK-09) needs a signed bundle with its Info.plist bound to the
    # signature; an unsigned copy fails `requestAuthorization` silently. Sparkle.framework is
    # re-signed ad-hoc here too, which is fine for a dev build.
    codesign --force --deep --sign - "$BUNDLE"
else
    echo "bundle-app.sh: signing with Developer ID identity $SIGN_IDENTITY" >&2
    ENTITLEMENTS_DIR="$ROOT/scripts/entitlements"
    sign() { codesign --force --options runtime --timestamp --sign "$SIGN_IDENTITY" "$@"; }

    # Inside-out, no --deep: the daemon and its link, the Sparkle helpers, the framework, the app.
    sign --entitlements "$ENTITLEMENTS_DIR/waggle-daemon.entitlements" "$BUNDLE/Contents/Resources/waggle"
    SPARKLE_B="$BUNDLE/Contents/Frameworks/Sparkle.framework/Versions/B"
    for helper in "$SPARKLE_B/XPCServices/Installer.xpc" "$SPARKLE_B/XPCServices/Downloader.xpc" \
                  "$SPARKLE_B/Autoupdate" "$SPARKLE_B/Updater.app"; do
        if [ -e "$helper" ]; then
            sign --preserve-metadata=entitlements "$helper"
        fi
    done
    sign "$BUNDLE/Contents/Frameworks/Sparkle.framework"
    sign --entitlements "$ENTITLEMENTS_DIR/waggle-app.entitlements" "$BUNDLE"

    codesign --verify --strict --deep --verbose=2 "$BUNDLE"
    spctl -a -vv "$BUNDLE" >&2 || echo "bundle-app.sh: spctl rejects the bundle until it is notarized (release.sh does that)" >&2
fi

echo "$BUNDLE"
